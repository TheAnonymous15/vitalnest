<script>
    document.getElementById('contact-form').addEventListener('submit', async function(e) {
        e.preventDefault();

        const submitBtn = this.querySelector('button[type="submit"]');
        const originalBtnText = submitBtn.innerHTML;

        // Disable button and show loading state
        submitBtn.disabled = true;
        submitBtn.innerHTML = '<i class="fas fa-spinner fa-spin mr-2"></i>Sending...';

        // Get form data
        const formData = {
            name: this.name.value.trim(),
            email: this.email.value.trim(),
            phone: this.phone.value.trim() || null,
            subject: this.subject.value || 'General Inquiry',
            message: this.message.value.trim()
        };

        try {
            // Send to API
            const response = await fetch('/gateway/routes/contact.php', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify(formData)
            });

            const result = await response.json();

            if (result.success) {
                // Show success message
                showNotification('Success!', result.message, 'success');
                this.reset();
            } else {
                showNotification('Error', result.message || 'Failed to send message', 'error');
            }
        } catch (error) {
            console.error('Error:', error);
            showNotification('Error', 'An error occurred. Please try again or contact us directly.', 'error');
        } finally {
            // Re-enable button
            submitBtn.disabled = false;
            submitBtn.innerHTML = originalBtnText;
        }
    });

    // Notification function
    function showNotification(title, message, type = 'info') {
        const notification = document.createElement('div');
        notification.className = `fixed top-4 right-4 z-50 max-w-md p-6 rounded-2xl shadow-2xl transform transition-all duration-500 ${
            type === 'success' ? 'bg-green-500' :
            type === 'error' ? 'bg-red-500' : 'bg-blue-500'
        }`;

        notification.innerHTML = `
            <div class="flex items-start gap-4">
                <div class="flex-shrink-0">
                    <i class="fas ${
                        type === 'success' ? 'fa-check-circle' :
                        type === 'error' ? 'fa-exclamation-circle' : 'fa-info-circle'
                    } text-2xl text-white"></i>
                </div>
                <div class="flex-1">
                    <h4 class="text-white font-bold mb-1">${title}</h4>
                    <p class="text-white/90 text-sm">${message}</p>
                </div>
                <button onclick="this.parentElement.parentElement.remove()" class="text-white/80 hover:text-white">
                    <i class="fas fa-times"></i>
                </button>
            </div>
        `;

        document.body.appendChild(notification);

        // Auto remove after 5 seconds
        setTimeout(() => {
            notification.style.opacity = '0';
            notification.style.transform = 'translateX(100%)';
            setTimeout(() => notification.remove(), 500);
        }, 5000);
    }
</script>

